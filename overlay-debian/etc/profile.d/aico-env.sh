# Load only the environment validated by aico-environment.service. Never
# source the user-managed file directly from a privileged login shell.
AICO_LOGIN_ENV_FILE=${AICO_SYSTEM_ENVIRONMENT:-/run/aico/system.env}
AICO_LOGIN_PROXY_ENV=${AICO_WIFI_PROXY_ENVIRONMENT:-/run/wifi_proxy/proxy-env}

case "$-" in
    *a*) AICO_LOGIN_RESTORE_ALLEXPORT=1 ;;
    *) AICO_LOGIN_RESTORE_ALLEXPORT=0 ;;
esac

set -a
if [ -r "${AICO_LOGIN_ENV_FILE}" ]; then
    . "${AICO_LOGIN_ENV_FILE}"
fi
if [ "${AICO_WIFI_PROXY_ENABLED:-1}" != 0 ] && [ -r "${AICO_LOGIN_PROXY_ENV}" ]; then
    . "${AICO_LOGIN_PROXY_ENV}"
    # Also support uppercase-only files generated by older business packages.
    # curl's HTTP path and apt expect the lowercase spellings.
    export http_proxy=${HTTP_PROXY:-}
    export https_proxy=${HTTPS_PROXY:-}
    export all_proxy=${ALL_PROXY:-}
    export no_proxy=${NO_PROXY:-}
fi
if [ "${AICO_LOGIN_RESTORE_ALLEXPORT}" != 1 ]; then
    set +a
fi

unset AICO_LOGIN_ENV_FILE AICO_LOGIN_PROXY_ENV AICO_LOGIN_RESTORE_ALLEXPORT
